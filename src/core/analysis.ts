/**
 * Analysis state – candidates for each cell and helper structures.
 */
import { FULL_MASK, EMPTY_MASK, digitsOf, hasDigit, maskOf } from './mask.ts';
import type { Grid } from './grid.ts';
import { PEERS, UNITS_OF_CELL, CELLS_OF_UNIT } from './geometry.ts';

/** Candidates for each cell as a 9‑bit mask. */
export type Candidates = Uint16Array; // 16 bits enough for 9 bits

/** Build initial candidates from a grid. */
export const initCandidates = (grid: Grid): Candidates => {
  const cand = new Uint16Array(81);
  for (let i = 0; i < 81; i++) {
    const v = grid[i];
    // For given cells, use a sentinel 0 mask to indicate solved (will be ignored by techniques).
    cand[i] = v === 0 ? FULL_MASK : 0;
  }
  // Apply initial constraints: remove digits present in peers.
  for (let i = 0; i < 81; i++) {
    const v = grid[i];
    if (v !== 0) {
      const mask = maskOf(v);
      for (const peer of PEERS[i]) {
        cand[peer] = cand[peer] & ~mask;
      }
    }
  }
  return cand;
};

/** Deduction generated by a technique. Currently only assignment deductions are used. */
/** Representation of a technique's effect.
 * `cell` and `digit` represent a forced assignment (used by most techniques).
 * Some techniques only eliminate candidates without assigning a digit. In that
 * case `eliminate` lists the cells and digits to be removed. The `cell`
 * property will be ignored for elimination‑only deductions and can be set to
 * `-1`.
 */
export interface Deduction {
  techniqueId: string;
  tier: number;
  /** Cell index for assignment deductions (0‑80). Use -1 if only eliminations. */
  cell: number;
  /** Digit assigned (1‑9). Ignored for elimination only. */
  digit: number;
  /** Optional elimination list: each entry removes `digit` from `cell`. */
  eliminate?: { cell: number; digit: number }[];
}

/** Apply a deduction (assign a digit) incrementally. */
/** Apply a deduction (assign a digit) and update candidate masks.
 * After assignment the cell is considered solved and its mask is cleared
 * (set to 0) so that further deduction detection ignores it.
 */
/** Apply a deduction to the candidate set.
 * Handles two kinds of deductions:
 * 1. Assignment: `cell` >= 0, `digit` > 0, `eliminate` undefined. The digit is
 *    assigned to the cell – peers lose that candidate and the cell mask is set
 *    to 0 (solved).
 * 2. Elimination‑only: `cell` is -1, `digit` ignored, `eliminate` is an array
 *    of `{cell, digit}` entries. Each entry removes the digit from the target
 *    cell's candidate mask.
 */
export const applyDeduction = (candidates: Candidates, d: Deduction): void => {
  if (d.eliminate && d.eliminate.length > 0) {
    // Eliminate candidates without assigning.
    for (const { cell, digit } of d.eliminate) {
      const mask = maskOf(digit);
      candidates[cell] = candidates[cell] & ~mask;
    }
    return;
  }
  const { cell, digit } = d;
  const mask = maskOf(digit);
  // Remove the digit from peers' candidates.
  for (const peer of PEERS[cell]) {
    candidates[peer] = candidates[peer] & ~mask;
  }
  // Mark the cell as solved – no further candidates.
  candidates[cell] = 0;
};

