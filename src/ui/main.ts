/**
 * Entry point for the UI. This file is referenced directly from index.html.
 * It sets up the DOM, registers the service worker (in production), and
 * starts the application state machine defined in `app.ts`.
 */
import { initApp } from "./app.ts";
import "./styles.css";

export function mount(): void {
  // Create root container for the app.
  const appRoot = document.createElement("div");
  appRoot.id = "app";
  document.body.appendChild(appRoot);

  // Initialise the application (UI, state machine, etc.)
  initApp(appRoot);

  // Register service worker if supported.
  if ("serviceWorker" in navigator) {
    // In production this will register the generated service worker.
    navigator.serviceWorker.register("./sw.js").catch(() => {
      // Sw registration failures are non‑blocking – ignore.
    });
  }
}
// Automatically mount the UI when this module is imported.
// This ensures the app starts both in development (direct script tag) and in
// the production bundle generated by Vite.
mount();
